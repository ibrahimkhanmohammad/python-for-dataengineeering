#   membership operators -> in , not in (return boolean value)

nums = [10, 20, 30, 40, 50]

#   in:  print True if element does, exists in a list if not False
print(20 in nums)
print(100 in nums)

#   not in:  print True if element does not, exists in a list if exists False
print(10 not in nums)
print(100 not in nums)